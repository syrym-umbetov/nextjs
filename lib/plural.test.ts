import { describe, expect, it } from 'vitest'
import { plural, pluralize } from './plural'

describe('plural', () => {
  it.each([
    [1, 'вопрос'], [2, 'вопроса'], [3, 'вопроса'], [4, 'вопроса'],
    [5, 'вопросов'], [9, 'вопросов'], [10, 'вопросов'],
  ])('%i → %s', (n, expected) => {
    expect(plural(n, 'вопрос', 'вопроса', 'вопросов')).toBe(expected)
  })

  it('числа второго десятка все дают форму множественного числа', () => {
    for (let n = 11; n <= 19; n += 1) {
      expect(plural(n, 'вопрос', 'вопроса', 'вопросов')).toBe('вопросов')
    }
  })

  it('согласование считается по последним двум цифрам', () => {
    expect(plural(21, 'вопрос', 'вопроса', 'вопросов')).toBe('вопрос')
    expect(plural(22, 'вопрос', 'вопроса', 'вопросов')).toBe('вопроса')
    expect(plural(25, 'вопрос', 'вопроса', 'вопросов')).toBe('вопросов')
    expect(plural(111, 'вопрос', 'вопроса', 'вопросов')).toBe('вопросов')
    expect(plural(121, 'вопрос', 'вопроса', 'вопросов')).toBe('вопрос')
  })

  it('ноль и отрицательные не ломают правило', () => {
    expect(plural(0, 'вопрос', 'вопроса', 'вопросов')).toBe('вопросов')
    expect(plural(-2, 'вопрос', 'вопроса', 'вопросов')).toBe('вопроса')
  })

  it('pluralize подставляет само число', () => {
    expect(pluralize(51, 'вопрос', 'вопроса', 'вопросов')).toBe('51 вопрос')
    expect(pluralize(22, 'вопрос', 'вопроса', 'вопросов')).toBe('22 вопроса')
  })
})
